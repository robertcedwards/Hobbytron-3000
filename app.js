function seed() {
  const st = {
    petName: 'Tronnie',
    hobbies: DEFAULT_HOBBIES.map((h) => ({ id: uid(), ...h })),
    knownDefaults: DEFAULT_HOBBIES.map((h) => h.name),
    sessions: [],
    categories: [...EXTRA_CATEGORIES],
    devices: [],
    ideas: [],
    hangar: { stamp: null, base: {}, seenIdeas: [] },
  };
  syncHangar(st, FLEET);
  return st;
}

// Bring older saved states up to date: add starter hobbies introduced since
// (unless the user already has or deleted them) and the Hangar sync record.
function migrate(st) {
  st.knownDefaults ??= [];
  for (const h of DEFAULT_HOBBIES) {
    if (st.knownDefaults.includes(h.name)) continue;
    st.knownDefaults.push(h.name);
    if (!st.hobbies.some((x) => x.name === h.name)) st.hobbies.push({ id: uid(), ...h });
  }
  for (const c of EXTRA_CATEGORIES) if (!st.categories.some((x) => x.key === c.key)) st.categories.push(c);
  st.hangar ??= { stamp: null, base: {}, seenIdeas: st.ideas.map((i) => i.title) };
  return st;
}

function load() {
  try {
    const raw = localStorage.getItem(STORE_KEY);
    if (raw) return migrate(JSON.parse(raw));
  } catch (e) { /* fall through to seed */ }
  return seed();
}

// Point devices whose hobby no longer exists (e.g. after importing an older
// export) back at the hobby their category feeds, matched by name.
function relinkDevices() {
  const ids = new Set(state.hobbies.map((h) => h.id));
  state.devices.forEach((d) => {
    if (d.hobbyId && ids.has(d.hobbyId)) return;
    d.hobbyId = state.hobbies.find((h) => h.name === CATEGORY_HOBBY[d.category])?.id || '';
  });
}

// ---------- Hangar sync ----------
// The Hangar (hangar/fleet.js, regenerated by scripts/sync-hangar.mjs) is the
// upstream. A three-way merge against the last-synced copy of each device
// (state.hangar.base) means upstream changes flow in while anything edited
// here (status, firmware, notes, hobby) is kept. Firmware histories union.

const HANGAR_FIELDS = ['name', 'category', 'model', 'platform', 'status', 'firmware', 'art', 'tagline', 'story', 'screen', 'highlights'];
const same = (a, b) => JSON.stringify(a ?? null) === JSON.stringify(b ?? null);

function fleetStamp(fleet) {
  const str = JSON.stringify([fleet.categories, fleet.devices, fleet.ideas]);
  let h = 5381;
  for (let i = 0; i < str.length; i++) h = ((h << 5) + h + str.charCodeAt(i)) | 0;
  return (h >>> 0).toString(36);
}

const historyKey = (x) => `${x.firmware}|${x.date}|${x.note}`;
function mergeHistory(local = [], upstream = []) {
  const seen = new Set(local.map(historyKey));
  const merged = [...local, ...upstream.filter((x) => !seen.has(historyKey(x)))];
  // Newest first; undated entries sink to the bottom. Stable for ties.
  return merged.map((x, i) => [x, i]).sort(([a, i], [b, j]) => (b.date || '').localeCompare(a.date || '') || i - j).map(([x]) => x);
}

function syncHangar(st, fleet) {
  const sum = { added: [], updated: [], kept: [], gone: [], ideas: 0 };
  const hobbyFor = (cat) => st.hobbies.find((h) => h.name === CATEGORY_HOBBY[cat])?.id || '';
  for (const c of fleet.categories || []) {
    const mine = st.categories.find((x) => x.key === c.key);
    if (mine) mine.label = c.label;
    else st.categories.splice(st.categories.findIndex((x) => EXTRA_CATEGORIES.some((e) => e.key === x.key)) >>> 0, 0, { ...c });
  }
  const upIds = new Set();
  for (const u of fleet.devices || []) {
    upIds.add(u.id);
    const base = st.hangar.base[u.id];
    const local = st.devices.find((d) => d.id === u.id);
    if (!local) {
      // A device we synced before but is gone locally was deleted here: respect that.
      if (!base) {
        st.devices.push({ ...structuredClone(u), history: structuredClone(u.history || []), hobbyId: hobbyFor(u.category) });
        sum.added.push(u.name);
      }
    } else {
      // No base yet (state from before sync existed): it was seeded from this fleet.
      const b = base || u;
      let changed = false;
      for (const f of HANGAR_FIELDS) {
        if (same(local[f], u[f])) continue;
        if (same(local[f], b[f])) { local[f] = structuredClone(u[f]); changed = true; }
        else if (!base || !same(b[f], u[f])) sum.kept.push(`${local.name}: ${f}`);
      }
      const hist = mergeHistory(local.history, u.history);
      if (hist.length !== (local.history || []).length) { local.history = hist; changed = true; }
      if (changed) sum.updated.push(local.name);
    }
    st.hangar.base[u.id] = structuredClone(u);
  }
  for (const id of Object.keys(st.hangar.base)) {
    if (upIds.has(id)) continue;
    const d = st.devices.find((x) => x.id === id);
    if (d) sum.gone.push(d.name);
    delete st.hangar.base[id];
  }
  for (const i of fleet.ideas || []) {
    if (st.hangar.seenIdeas.includes(i.title)) continue;
    st.hangar.seenIdeas.push(i.title);
    if (st.ideas.some((x) => x.title === i.title)) continue;
    const ids = (i.devices || []).map((n) => st.devices.find((d) => d.name === n)?.id).filter(Boolean);
    st.ideas.push({ id: uid(), title: i.title, note: i.note || '', deviceIds: ids, done: false });
    sum.ideas++;
  }
  st.hangar.stamp = fleetStamp(fleet);
  st.hangar.syncedAt = new Date().toISOString();
  return sum;
}

function syncReport(sum) {
  const parts = [];
  if (sum.added.length) parts.push(`Added ${sum.added.length}: ${sum.added.join(', ')}`);
  if (sum.updated.length) parts.push(`Updated ${sum.updated.length}: ${sum.updated.join(', ')}`);
  if (sum.ideas) parts.push(`${sum.ideas} new idea${sum.ideas > 1 ? 's' : ''}`);
  if (sum.kept.length) parts.push(`Kept your edits over the Hangar's for ${sum.kept.join('; ')}`);
  if (sum.gone.length) parts.push(`No longer in the Hangar (kept here): ${sum.gone.join(', ')}`);
  return parts.length ? parts.join('\n') : 'Already up to date.';
}

