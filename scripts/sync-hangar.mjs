#!/usr/bin/env node
// Sync hangar/fleet.js with The Hangar.
//
//   node scripts/sync-hangar.mjs <source> [--dry-run] [--into <hangar.html>]
//
// <source> is one of:
//   - The Hangar artifact's HTML (its FLEET data and device SVGs are pulled out)
//   - a fleet JSON from Hobbytron (Data → "Export fleet for the Hangar")
//   - another fleet.js
//
// --dry-run  print what would change without writing anything
// --into     also write <hangar.html> back out as <name>.synced.html with the
//            new FLEET (and SVGs) swapped in, ready to republish the artifact.
//
// The FLEET/SVG block is evaluated with node:vm. That is not a security
// sandbox, so only point this at your own Hangar files.

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FLEET_JS = path.join(ROOT, 'hangar', 'fleet.js');

// Index just past the `}` matching the `{` at `open`, skipping strings and comments.
function matchBrace(text, open) {
  let depth = 0;
  for (let i = open; i < text.length; i++) {
    const c = text[i];
    if (c === '"' || c === "'" || c === '`') {
      for (i++; i < text.length && text[i] !== c; i++) if (text[i] === '\\') i++;
    } else if (c === '/' && text[i + 1] === '/') {
      i = text.indexOf('\n', i); if (i < 0) break;
    } else if (c === '/' && text[i + 1] === '*') {
      i = text.indexOf('*/', i + 2) + 1; if (i <= 0) break;
    } else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return i + 1;
  }
  throw new Error('unbalanced braces in the FLEET block');
}

// Locate `window.FLEET = {...}` plus the SVG map that follows it
// (`var SVGS = {...}` in the artifact, `window.HANGAR_SVGS = {...}` here).
function findBlock(text) {
  const head = /^[ \t]*window\.FLEET\s*=\s*/m.exec(text);
  if (!head) throw new Error('no `window.FLEET = …` block found');
  const start = head.index;
  let end = matchBrace(text, head.index + head[0].length);
  const svg = /^\s*;?\s*(?:var SVGS|window\.HANGAR_SVGS)\s*=\s*/.exec(text.slice(end));
  if (svg) end = matchBrace(text, end + svg[0].length);
  if (text[end] === ';') end++;
  return { start, end, code: text.slice(start, end) };
}

function evalBlock(code) {
  const ctx = { window: {} };
  vm.runInNewContext(code, ctx, { timeout: 2000 });
  if (!ctx.window.FLEET) throw new Error('FLEET block did not define window.FLEET');
  return { fleet: ctx.window.FLEET, svgs: ctx.SVGS || ctx.window.HANGAR_SVGS || null };
}

function load(file) {
  const text = fs.readFileSync(file, 'utf8');
  if (file.endsWith('.json')) {
    const fleet = JSON.parse(text);
    if (!Array.isArray(fleet.devices)) throw new Error(`${file} has no devices array`);
    return { fleet: { categories: [], ideas: [], ...fleet }, svgs: null };
  }
  return evalBlock(findBlock(text).code);
}

function renderFleetJs(fleet, svgs) {
  const svgLines = Object.entries(svgs).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(',\n');
  return `// The Hangar's fleet data and hand-coded device SVGs. Generated by
// scripts/sync-hangar.mjs; regenerate rather than hand-editing.
// Hobbytron merges this into each browser's saved Hangar (Hangar → Sync).
window.FLEET = ${JSON.stringify(fleet, null, 2)};

window.HANGAR_SVGS = {
${svgLines}
};
`;
}

function diff(oldF, newF) {
  const byId = (f) => new Map((f.devices || []).map((d) => [d.id, d]));
  const a = byId(oldF), b = byId(newF);
  const lines = [];
  for (const [id, d] of b) {
    if (!a.has(id)) { lines.push(`+ ${d.name}`); continue; }
    const o = a.get(id);
    const fields = [...new Set([...Object.keys(o), ...Object.keys(d)])].filter((k) => JSON.stringify(o[k]) !== JSON.stringify(d[k]));
    if (fields.length) lines.push(`~ ${d.name} (${fields.join(', ')})`);
  }
  for (const [id, d] of a) if (!b.has(id)) lines.push(`- ${d.name}`);
  const oldIdeas = new Set((oldF.ideas || []).map((i) => i.title));
  for (const i of newF.ideas || []) if (!oldIdeas.has(i.title)) lines.push(`+ idea: ${i.title}`);
  const newIdeas = new Set((newF.ideas || []).map((i) => i.title));
  for (const i of oldF.ideas || []) if (!newIdeas.has(i.title)) lines.push(`- idea: ${i.title}`);
  return lines;
}

const args = process.argv.slice(2);
const flag = (name) => { const i = args.indexOf(name); return i < 0 ? null : args.splice(i, 2)[1] ?? ''; };
const dry = args.includes('--dry-run') && args.splice(args.indexOf('--dry-run'), 1);
const into = flag('--into');
const source = args[0];
if (!source) {
  console.error('usage: node scripts/sync-hangar.mjs <hangar.html | fleet.json | fleet.js> [--dry-run] [--into <hangar.html>]');
  process.exit(1);
}

const current = fs.existsSync(FLEET_JS) ? load(FLEET_JS) : { fleet: { categories: [], devices: [], ideas: [] }, svgs: {} };
const incoming = load(source);
// A Hobbytron export carries no art; keep the SVGs we already have, plus any new ones.
const svgs = { ...current.svgs, ...(incoming.svgs || {}) };
const fleet = incoming.fleet;

const changes = diff(current.fleet, fleet);
console.log(changes.length ? changes.join('\n') : 'hangar/fleet.js is already up to date.');
const missingArt = fleet.devices.filter((d) => d.art && !svgs[d.art]).map((d) => d.name);
if (missingArt.length) console.warn(`warning: no SVG for ${missingArt.join(', ')}`);

if (!dry) {
  if (changes.length || JSON.stringify(current.svgs) !== JSON.stringify(svgs)) {
    fs.writeFileSync(FLEET_JS, renderFleetJs(fleet, svgs));
    console.log(`wrote ${path.relative(process.cwd(), FLEET_JS)}`);
  }
  if (into) {
    const html = fs.readFileSync(into, 'utf8');
    const { start, end } = findBlock(html);
    const block = `window.FLEET = ${JSON.stringify(fleet, null, 2)};\n\n\nvar SVGS = ${JSON.stringify(svgs)};`;
    const out = into.replace(/\.html?$/i, '') + '.synced.html';
    fs.writeFileSync(out, html.slice(0, start) + block + html.slice(end));
    console.log(`wrote ${out}`);
  }
}
